def get_json(url, tries=4):
    delay = 8
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA, 'Accept': 'application/json'})
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code == 429 and i < tries - 1:
                time.sleep(delay)
                delay *= 2
                continue
            raise
        except Exception:
            if i == tries - 1:
                raise
            time.sleep(delay)
            delay *= 2
    return None


def summary_image(title):
    """Lead image via the action API at a fixed 1280 px width.

    The width matters: Wikimedia now only serves a fixed set of thumbnail sizes and rejects
    other requests, so the URL has to be generated by the API rather than guessed.
    """
    q = urllib.parse.urlencode({
        'action': 'query', 'format': 'json', 'redirects': '1', 'titles': title,
        'prop': 'pageimages', 'piprop': 'thumbnail', 'pithumbsize': '1280'
    })
    d = get_json('https://en.wikipedia.org/w/api.php?' + q)
    pages = ((d or {}).get('query') or {}).get('pages') or {}
    for p in pages.values():
        if 'missing' in p:
            return None
        thumb = (p.get('thumbnail') or {}).get('source')
        if thumb:
            return thumb, p.get('title', title)
    return None


def commons_meta_from_url(src):
    """Extract the file name from a Wikimedia image URL and read its licence."""
    m = re.search(r'/commons/(?:thumb/)?[0-9a-f]/[0-9a-f]{2}/([^/]+)', src)
    if not m:
        return {}
    name = urllib.parse.unquote(m.group(1))
    if name.startswith(('thumb/', )):
        name = name.split('/')[-1]
    q = urllib.parse.urlencode({
        'action': 'query', 'format': 'json', 'titles': 'File:' + name,
        'prop': 'imageinfo', 'iiprop': 'extmetadata'
    })
    d = get_json('https://commons.wikimedia.org/w/api.php?' + q)
    pages = ((d or {}).get('query') or {}).get('pages') or {}
    for p in pages.values():
        info = (p.get('imageinfo') or [{}])[0]
        meta = info.get('extmetadata') or {}
        return {
            'license': (meta.get('LicenseShortName') or {}).get('value', ''),
            'artist': re.sub('<[^>]+>', '', (meta.get('Artist') or {}).get('value', '')).strip()[:90],
            'file': name,
        }
    return {'file': name}


def download(src, dest, tries=3):
    """Fetch through the images.weserv.nl resize proxy.

    Wikimedia applies a hard rate limit to this host on high volume, and it only serves a
    fixed set of thumbnail widths. The proxy fetches and resizes server side, which solves
    both problems and gives a predictable 900 px JPEG.
    """
    proxied = 'https://wsrv.nl/?' + urllib.parse.urlencode({'url': src, 'w': '900', 'output': 'jpg', 'q': '80'})
    delay = 8
    for i in range(tries):
        try:
            req = urllib.request.Request(proxied, headers={'User-Agent': UA})
            with urllib.request.urlopen(req, timeout=60) as r:
                data = r.read()
            with open(dest, 'wb') as f:
                f.write(data)
            return len(data)
        except urllib.error.HTTPError as e:
            if e.code in (429, 502, 503) and i < tries - 1:
                print('      proxy busy %d, waiting %ds' % (e.code, delay), flush=True)
                time.sleep(delay)
                delay *= 2
                continue
            raise
    return 0


def main():
    only = sys.argv[1:] or list(ARTICLES)
    results = json.load(open(JSON_PATH)) if os.path.exists(JSON_PATH) else {}
    for key in only:
        art = ARTICLES.get(key)
        if not art:
            continue
        if os.path.exists(os.path.join(OUT, key + '.jpg')) and key in results:
            print('SKIP %-12s already have it' % key, flush=True)
            continue
        try:
            found = summary_image(art)
        except Exception as e:
            print('ERR  %-12s %s' % (key, str(e)[:70]), flush=True)
            time.sleep(12)
            continue
        if not found:
            print('MISS %-12s %s' % (key, art), flush=True)
            time.sleep(3)
            continue
        src, page_title = found
        # Wikimedia only serves a fixed set of thumbnail widths; 1280 is one of them.
        # Upgrade to 1280 and fall back to whatever the API handed us.
        big = re.sub(r'/(\d+)px-', '/1280px-', src)
        dest = os.path.join(OUT, key + '.jpg')
        size = 0
        for candidate in ([big, src] if big != src else [src]):
            try:
                size = download(candidate, dest)
                if size and size > 6000:
                    src = candidate
                    break
            except Exception as e:
                print('DLERR %-11s %s' % (key, str(e)[:50]), flush=True)
        if not size or size < 6000:
            print('FAIL %-12s no usable image' % key, flush=True)
            if os.path.exists(dest):
                os.remove(dest)
            continue
        # normalise size so the repository stays small
        os.system('ffmpeg -loglevel error -y -i %s -vf "scale=900:-1" -q:v 6 %s.tmp.jpg && mv %s.tmp.jpg %s'
                  % (dest, dest, dest, dest))
        final = os.path.getsize(dest)
        meta = {}
        try:
            meta = commons_meta_from_url(src)
        except Exception:
            pass
        results[key] = {
            'key': key, 'file': dest, 'article': page_title, 'title': meta.get('file', page_title),
            'license': meta.get('license', ''), 'artist': meta.get('artist', ''),
            'page': 'https://en.wikipedia.org/wiki/' + urllib.parse.quote(page_title.replace(' ', '_')),
            'source': 'wikipedia', 'bytes': final,
        }
        print('OK   %-12s %-9s %d KB' % (key, meta.get('license', '?')[:9], final // 1024), flush=True)
        json.dump(results, open(JSON_PATH, 'w'), indent=1)
        time.sleep(6)
    json.dump(results, open(JSON_PATH, 'w'), indent=1)
    print('\n%d photos, %.1f MB' % (len(results), sum(r['bytes'] for r in results.values()) / 1e6), flush=True)


if __name__ == '__main__':
    main()
