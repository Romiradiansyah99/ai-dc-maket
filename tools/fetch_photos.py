"""Fetch one freely licensed reference photo per equipment type.

Uses the Wikipedia REST summary endpoint (lead image of the matching article), which is
curated, topical and rate limit friendly. Licence and author are captured from Commons
for attribution. Hides nothing: if an article has no image, the key is reported as MISS
and the panel simply omits the figure.
"""
