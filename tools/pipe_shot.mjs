import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath:'/usr/bin/chromium', headless:'shell', args:['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage(); await p.setViewport({width:1500,height:950, deviceScaleFactor:2});
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('http://127.0.0.1:8813/', {waitUntil:'domcontentloaded'});
await new Promise(r=>setTimeout(r,5000));
await p.evaluate(()=>{ document.getElementById('chkCables').click(); const a=window.__app; a.nav.focus(a.scene.position.clone().set(-9,8,-9.75), 2.4); });
await new Promise(r=>setTimeout(r,1000));
await p.screenshot({path:'/tmp/pipes_tech.png'});
await p.evaluate(()=>{ document.querySelector('[data-view="risers"]').click(); });
await new Promise(r=>setTimeout(r,1400));
await p.screenshot({path:'/tmp/pipes_shaft.png'});
console.log(JSON.stringify({errs}));
await b.close();
