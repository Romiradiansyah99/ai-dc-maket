#!/usr/bin/env python3
"""Turn media/photos.json into:
   1. src/data/photos.js  (credit line shown under each figure in the panel)
   2. docs/PHOTO-CREDITS.md (full attribution table for the repository)
Run after tools/fetch_photos.py.
"""
import json, os

ROOT = '/tmp/aidc'
SRC = os.path.join(ROOT, 'media/photos.json')
data = json.load(open(SRC)) if os.path.exists(SRC) else {}

lines = ['// Generated by tools/make_photos_js.py. Do not edit by hand.',
         '// Map of equipment key to reference photograph metadata.', '',
         'export const PHOTOS = {']
for k in sorted(data):
    r = data[k]
    if not os.path.exists(r['file']):
        continue
    artist = (r.get('artist') or 'Wikimedia contributor').replace("'", "\\'")[:80]
    lic = (r.get('license') or 'see source').replace("'", "\\'")
    lines.append("  %s: { credit: '%s', licence: '%s', page: '%s' }," % (k, artist, lic, r['page']))
lines.append('};')
open(os.path.join(ROOT, 'src/data/photos.js'), 'w').write('\n'.join(lines) + '\n')

rows = ['# Photo credits', '',
        'Reference photographs are the property of their authors, used here under the licence shown.',
        'Each image is the lead image of the linked article and was checked against the equipment it illustrates.', '',
        '| Equipment | Source article | Author | Licence |', '|---|---|---|---|']
for k in sorted(data):
    r = data[k]
    if not os.path.exists(r['file']):
        continue
    art = r.get('article', '')
    rows.append('| %s | [%s](%s) | %s | %s |' % (
        k, art, r['page'], (r.get('artist') or 'n/a'), (r.get('license') or 'see article')))
rows += ['', 'Photographs are fetched with `tools/fetch_photos.py` and normalised to 900 px wide.', '']
open(os.path.join(ROOT, 'docs/PHOTO-CREDITS.md'), 'w').write('\n'.join(rows))

print('%d entries written' % len([k for k in data if os.path.exists(data[k]['file'])]))
